const DICTS: Record<Lang, Partial<Dict>> = { en, pl, ro, es, pt, it, fr, uk };

/** Full dictionary for a language, English filling any gaps. */
export function dict(lang: Lang): Dict {
  return { ...en, ...DICTS[lang] } as Dict;
}

/** Fill `{placeholders}`. */
export function fill(s: string, vars: Record<string, string | number> = {}) {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** Pick the best language from an Accept-Language header. */
export function fromAcceptLanguage(header: string | null | undefined): Lang {
  for (const part of (header ?? "").split(",")) {
    const code = part.trim().slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return "en";
}

export function dateIn(lang: Lang, iso: string, opts: Intl.DateTimeFormatOptions = { day: "numeric", month: "short" }) {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, m - 1, d).toLocaleDateString(LANGS[lang].locale, opts);
}
