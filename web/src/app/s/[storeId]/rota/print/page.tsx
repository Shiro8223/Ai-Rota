import { notFound } from "next/navigation";
import { requireStore } from "@/lib/auth";
import { db } from "@/lib/db";
import { dayDate, hours, isMonday, prettyDate, shiftsForStore, weekLabel } from "@/lib/time";
import { DAY_LABEL, DAYS } from "@/lib/types";
import { PrintButton, RoleSelect } from "./print-button";
import { storeStaff } from "@/lib/org";
import { storeRoles } from "@/lib/team";

export default async function PrintRota({ params, searchParams }: { params: Promise<{ storeId: string }>; searchParams: Promise<{ week?: string; role?: string }> }) {
  const { storeId } = await params;
  const { week, role: roleId } = await searchParams;
  const { store } = await requireStore(storeId, ["rota.view", "rota.edit", "rota.publish"]);
  if (!week || !isMonday(week)) notFound();
  const d = await db();
  const [rota] = await d.list("rotas", { storeId, weekStart: week });
  if (!rota) notFound();
  // Own staff plus people visiting from sister sites; roles matched by name across sites.
  const employees = (await storeStaff(store)).sort((a, b) => a.name.localeCompare(b.name));
  const jobRoles = (await storeRoles(storeId)).filter((r) => r.category === "job");
  const role = jobRoles.find((r) => r.id === roleId) ?? null;
  const allRoles = role ? (await Promise.all([...new Set(employees.map((e) => e.storeId))].map((id) => storeRoles(id)))).flat() : [];
  const hasRole = (e: (typeof employees)[number]) => !role || allRoles.some((r) => (e.roleIds ?? []).includes(r.id) && r.name.toLowerCase() === role.name.toLowerCase());
  const shifts = Object.fromEntries(shiftsForStore(store).map((s) => [s.id, s]));
  const days = DAYS.filter((day) => Object.values(shifts).some((s) => s.day === day));
  const people = employees.filter((e) => rota.assignments.some((a) => a.employeeId === e.id) && hasRole(e));

  return (
    <div className="mx-auto max-w-[1100px] bg-white p-6 text-[12px]">
      <div className="mb-3 flex items-end justify-between">
        <div>
          <h1 className="text-xl font-semibold">{store.name} · Rota{role ? ` · ${role.name}` : ""}</h1>
          <p className="text-stone-600">
            Week {weekLabel(week)} · {rota.status === "approved" ? `Approved by ${rota.approvedBy} on ${prettyDate(rota.approvedAt!.slice(0, 10))} (v${rota.version})` : "DRAFT - not yet approved"}
          </p>
        </div>
        <div className="flex items-center gap-3">
          <RoleSelect roles={jobRoles.map((r) => ({ id: r.id, name: r.name }))} value={role?.id ?? ""} />
          <PrintButton />
        </div>
      </div>
      <table className="w-full border-collapse">
        <thead>
          <tr>
            <th className="border border-stone-400 bg-stone-100 px-2 py-1 text-left">Name</th>
            {days.map((day) => (
              <th key={day} className="border border-stone-400 bg-stone-100 px-2 py-1">
                {DAY_LABEL[day]} {prettyDate(dayDate(week, day))}
              </th>
            ))}
            <th className="border border-stone-400 bg-stone-100 px-2 py-1">Hours</th>
          </tr>
        </thead>
        <tbody>
          {people.map((e) => {
            const mine = rota.assignments.filter((a) => a.employeeId === e.id).map((a) => shifts[a.shiftId]).filter(Boolean);
            const total = mine.reduce((n, s) => n + s.minutes, 0);
            return (
              <tr key={e.id}>
                <td className="border border-stone-400 px-2 py-1 font-medium">
                  {e.name} <span className="font-normal text-stone-500">{e.role}</span>
                </td>
                {days.map((day) => {
                  const s = mine.find((x) => x.day === day);
                  return (
                    <td key={day} className="border border-stone-400 px-2 py-1 text-center">
                      {s ? (
                        <>
                          <div className="font-medium">{s.name}</div>
                          <div>{s.start}–{s.end}</div>
                        </>
                      ) : (
                        <span className="text-stone-300">–</span>
                      )}
                    </td>
                  );
                })}
                <td className="border border-stone-400 px-2 py-1 text-center tabular-nums">{hours(total)}</td>
              </tr>
            );
          })}
          {!people.length && <tr><td colSpan={days.length + 2} className="border border-stone-400 px-2 py-4 text-center text-stone-500">No one with this role is on the rota this week.</td></tr>}
        </tbody>
      </table>
      <p className="mt-3 text-[10px] text-stone-500">Generated by Rota Agent. The manager approves the final rota; swaps must be approved before they apply.</p>
    </div>
  );
}
